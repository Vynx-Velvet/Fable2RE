"""Declarations and bridges for the native entry points (Phase B1).

    python tools/lift/native_gen.py

Writes (only when changed):
  Fable2Recomp/lifted/native_decls.h        a prototype of n_<name> for every analysed function
  Fable2Recomp/lifted/native_bridges.N.cpp  weak n_<name> for every function: arguments -> context ->
                                            <name>(ctx, base) -> result. The lifted definition of a function
                                            (strong) replaces its bridge; for hooked, hand-written and
                                            still-recompiled functions the bridge is the native entry point.
Both follow tools/lift/cache/signatures.pkl and the whole-game summaries: regenerate after either changes.
"""
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
import lift  # noqa: E402
import names as names_  # noqa: E402
import regs  # noqa: E402

OUT = os.path.normpath(os.path.join(HERE, '..', '..', 'Fable2Recomp', 'lifted'))
PER_FILE = 8000


def write_if_changed(path, text):
    if os.path.exists(path):
        with open(path, encoding='utf-8', newline='') as f:
            if f.read() == text:
                return False
    with open(path, 'w', encoding='utf-8', newline='\n') as f:
        f.write(text)
    return True


def prototypes():
    """native name -> prototype text, for every function with a native entry point."""
    out = {}
    sg = lift.signatures()
    for n in sg.get('params', ()):
        sig = lift.native_sig(n)
        if sig is None:
            continue
        pbits, rbit = sig
        rreg = regs.names(rbit)[0] if rbit else None
        types = ''.join(', ' + lift.param_type(n, reg) for reg in lift.param_order(pbits))
        native = names_.native_name(n)
        out[native] = f'{lift.ret_type(n, rreg)} {native}(PPCContext& ctx, uint8_t* base{types});'
    return out


def main():
    sg = lift.signatures()
    names = sorted(n for n in sg['params'] if lift.native_sig(n) is not None)
    decls = ['// Native entry points of the game functions (generated by tools/lift/native_gen.py - do not edit).',
             '#pragma once', '']
    bridges = []
    for n in names:
        pbits, rbit = lift.native_sig(n)
        rreg = regs.names(rbit)[0] if rbit else None
        rtype = lift.ret_type(n, rreg)
        plist = [(reg, lift.param_type(n, reg)) for reg in lift.param_order(pbits)]
        native = names_.native_name(n)
        decls.append(f'{rtype} {native}(PPCContext& ctx, uint8_t* base{"".join(", " + t for _, t in plist)});')
        body = ''.join(f' ctx.{reg}.{"f64" if reg.startswith("f") else "u64"} = {reg};' for reg, _ in plist)
        ret = ''
        if rreg:
            ret = f' return ctx.{rreg}.' + ('f64' if rreg.startswith('f') else 'u64' if rtype == 'uint64_t' else 'u32') + ';'
        bridges.append(f'F2_BRIDGE {rtype} {native}(PPCContext& ctx, uint8_t* base'
                       f'{"".join(f", {t} {reg}" for reg, t in plist)}) {{{body} {n}(ctx, base);{ret} }}')
    changed = write_if_changed(os.path.join(OUT, 'native_decls.h'), '\n'.join(decls) + '\n')
    files = 0
    for k in range(0, len(bridges), PER_FILE):
        text = ('// Bridges from native calls to functions that are not lifted natively (generated by\n'
                '// tools/lift/native_gen.py - do not edit). Weak: the lifted definition replaces its bridge.\n'
                '#include "lifted/lifted.h"\n#include "lifted/native_decls.h"\n'
                '#define F2_BRIDGE __attribute__((weak, noinline))\n\n' + '\n'.join(bridges[k:k + PER_FILE]) + '\n')
        changed |= write_if_changed(os.path.join(OUT, f'native_bridges.{k // PER_FILE}.cpp'), text)
        files += 1
    print(f'{len(names)} native entry points; {files} bridge files' + ('' if changed else ' (unchanged)'))


if __name__ == '__main__':
    main()
