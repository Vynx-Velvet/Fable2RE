#!/usr/bin/env python3
"""Generate the game-tuning table: every Lua binding (any table) whose whole body is "store the
argument into one global" - Fable II's live tuning values (combat, magic, experience orbs, hero
movement, physics limits, debug switches...).

Ground truth is the recompiled PowerPC (the `// insn` comments of Fable2Recomp/generated), not the
decompiler: the function must be exactly
    lis rA,HI ; st{b,h,w,fs} rS,LO(rA) ; blr        (rS = r3 for integers, f1 for floats)
Output:
  Fable2Recomp/src/game/tuning/tuning_table.inc   X(Name, guest address, type, setter address)
  research/catalog/tuning.tsv
  research/catalog/converted.tsv                  setters marked "rewritten" (module game/tuning)
Usage: python tools/convert/gen_tuning.py
"""
import csv
import json
import os
import re

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
GEN = os.path.join(ROOT, 'Fable2Recomp', 'generated')
csv.field_size_limit(10 ** 8)


def s16(v):
    return v - 0x10000 if v & 0x8000 else v


def main():
    db = json.load(open(os.path.join(ROOT, 'research', 'symbols', 'func_db.json')))
    bindings = list(csv.DictReader(open(os.path.join(ROOT, 'research', 'symbols', 'lua_bindings_named.tsv'),
                                        encoding='utf-8'), delimiter='\t'))
    files = {}
    rows = []
    for b in bindings:
        a = b['function']
        f = db.get(a)
        if not f or f['ninsn'] > 4:
            continue
        path = os.path.join(GEN, f['file'])
        if path not in files:
            files[path] = open(path, encoding='utf-8', errors='replace').read().split('\n')
        lines = files[path]
        insns = []
        for line in lines[f['line'] - 1:f['line'] + 40]:
            m = re.match(r'^\s*// (\w+\.?)\s+(.*)$', line)
            if m:
                insns.append((m.group(1), m.group(2).replace(' ', '')))
            if line.startswith('}'):
                break
        if len(insns) != 3 or insns[0][0] != 'lis' or insns[2][0] != 'blr':
            continue
        op, args = insns[1]
        m = re.match(r'(r\d+|f\d+),(-?\w+)\((r\d+)\)$', args)
        lis = re.match(r'(r\d+),(-?\w+)$', insns[0][1])
        if not m or not lis or m.group(3) != lis.group(1):
            continue
        types = {'stb': ('uint8_t', 'r3'), 'sth': ('uint16_t', 'r3'), 'stw': ('uint32_t', 'r3'),
                 'stfs': ('float', 'f1')}
        if op not in types or m.group(1) != types[op][1]:
            continue
        addr = ((int(lis.group(2), 0) << 16) + s16(int(m.group(2), 0) & 0xFFFF)) & 0xFFFFFFFF
        name = b['name'][3:] if b['name'].startswith('Set') else b['name']
        ctype = types[op][0]
        if ctype == 'uint8_t' and re.search(r'Enabled?$|^Draw|^Use|^Allow|^Is|^Enable', name):
            ctype = 'bool'
        rows.append((name, addr, ctype, a, f"{b['table']}.{b['name']}"))
    # One entry per global (several bindings may write the same value: keep the first name).
    seen, unique = set(), []
    for r in sorted(rows, key=lambda r: (r[1], r[0])):
        if r[1] in seen:
            continue
        seen.add(r[1])
        unique.append(r)
    out_dir = os.path.join(ROOT, 'Fable2Recomp', 'src', 'game', 'tuning')
    os.makedirs(out_dir, exist_ok=True)
    with open(os.path.join(out_dir, 'tuning_table.inc'), 'w', encoding='utf-8', newline='\n') as f:
        f.write('// Generated by tools/convert/gen_tuning.py - Fable II tuning values written by Lua setters.\n')
        f.write('// X(Name, guest address, C type, setter function (guest), Lua binding)\n')
        for name, addr, ctype, setter, lua in unique:
            f.write(f'X({name}, 0x{addr:08X}, {ctype}, {setter}, "{lua}")\n')
    with open(os.path.join(ROOT, 'research', 'catalog', 'tuning.tsv'), 'w', encoding='utf-8', newline='\n') as f:
        f.write('name\taddress\ttype\tsetter\tlua\n')
        for name, addr, ctype, setter, lua in unique:
            f.write(f'{name}\t{addr:08X}\t{ctype}\t{setter}\t{lua}\n')
    conv_path = os.path.join(ROOT, 'research', 'catalog', 'converted.tsv')
    conv = {}
    if os.path.exists(conv_path):
        for r in csv.DictReader(open(conv_path, encoding='utf-8'), delimiter='\t'):
            conv[r['address']] = r
    for name, addr, ctype, setter, lua in unique:
        conv[setter] = {'address': setter, 'name': f'Lua_{lua.replace(".", "_")}', 'status': 'rewritten',
                        'module': 'Fable2Recomp/src/game/tuning/tuning.cpp'}
    with open(conv_path, 'w', encoding='utf-8', newline='\n') as f:
        f.write('address\tname\tstatus\tmodule\n')
        for a in sorted(conv):
            r = conv[a]
            f.write(f"{a}\t{r['name']}\t{r['status']}\t{r['module']}\n")
    types = {}
    for r in unique:
        types[r[2]] = types.get(r[2], 0) + 1
    print(f'{len(unique)} tuning values ({len(rows)} setters): {types}')


if __name__ == '__main__':
    main()
